//! Generates the stabilized-text table (`src/stabilized_text.rs`) from the
//! one Unicode data file the package holds: the `DerivedAge.txt` of the
//! single version directory under `data/unicode/`, a copy of the Unicode
//! Character Database file of that version, its license beside it
//! (`data/unicode/LICENSE-UNICODE`). Nothing of the table is written by
//! hand: the code points the file lists as assigned, at any age, merged
//! into sorted inclusive ranges, and the version its header names, are
//! written to `$OUT_DIR/unicode_assigned.rs`, which the library includes.
//! The library checks at compile time that this version is the one the
//! pinned `unicode-normalization` normalizes by.
//!
//! A malformed file, a header naming another version than its directory,
//! or any number of version directories but one, fails the build naming
//! what it found.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// The directory holding one directory per Unicode version.
const UNICODE_DATA: &str = "data/unicode";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={UNICODE_DATA}");
    let version_dir = only_version_directory(Path::new(UNICODE_DATA));
    let path = version_dir.join("DerivedAge.txt");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{} cannot be read: {error}", path.display()));
    let version = header_version(&text, &path);
    let directory = version_dir
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_else(|| panic!("{} has no UTF-8 name", version_dir.display()));
    let named = format!("{}.{}.{}", version.0, version.1, version.2);
    if directory != named {
        panic!(
            "{} names version {named}, but lies in the directory of version {directory}",
            path.display()
        );
    }
    let ranges = merged(assigned_ranges(&text, &path));
    let mut out = String::new();
    out.push_str("// Generated by build.rs from ");
    out.push_str(&path.display().to_string());
    out.push_str(". Do not edit.\n\n");
    out.push_str("/// The Unicode version whose `DerivedAge.txt` this table is generated\n");
    out.push_str("/// from, as the file's header names it.\n");
    out.push_str(&format!(
        "pub(crate) const DERIVED_AGE_VERSION: (u8, u8, u8) = ({}, {}, {});\n\n",
        version.0, version.1, version.2
    ));
    out.push_str("/// Every code point assigned in that version, at any age, as sorted,\n");
    out.push_str("/// disjoint, non-adjacent inclusive ranges.\n");
    out.push_str("pub(crate) const ASSIGNED: &[(u32, u32)] = &[\n");
    for (start, end) in &ranges {
        out.push_str(&format!("    (0x{start:04X}, 0x{end:04X}),\n"));
    }
    out.push_str("];\n");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let target = out_dir.join("unicode_assigned.rs");
    fs::write(&target, out)
        .unwrap_or_else(|error| panic!("{} cannot be written: {error}", target.display()));
}

/// The one version directory under `root`; none, or more than one, fails
/// the build naming every entry found.
fn only_version_directory(root: &Path) -> PathBuf {
    let entries = fs::read_dir(root)
        .unwrap_or_else(|error| panic!("{} cannot be read: {error}", root.display()));
    let mut directories: Vec<PathBuf> = entries
        .map(|entry| {
            entry
                .unwrap_or_else(|error| panic!("{} cannot be listed: {error}", root.display()))
                .path()
        })
        .filter(|path| path.is_dir())
        .collect();
    directories.sort();
    match directories.as_slice() {
        [only] => only.clone(),
        found => panic!(
            "{} must hold exactly one Unicode version directory; found {found:?}",
            root.display()
        ),
    }
}

/// The version the file's first line names, `# DerivedAge-X.Y.Z.txt`.
fn header_version(text: &str, path: &Path) -> (u8, u8, u8) {
    let first = text.lines().next().unwrap_or_default();
    let version = first
        .strip_prefix("# DerivedAge-")
        .and_then(|rest| rest.strip_suffix(".txt"))
        .unwrap_or_else(|| {
            panic!(
                "{}: the first line {first:?} is not a DerivedAge header",
                path.display()
            )
        });
    let parts: Vec<u8> = version
        .split('.')
        .map(|part| {
            part.parse().unwrap_or_else(|error| {
                panic!(
                    "{}: version {version:?} is not three numbers: {error}",
                    path.display()
                )
            })
        })
        .collect();
    match parts.as_slice() {
        [major, minor, update] => (*major, *minor, *update),
        _ => panic!(
            "{}: version {version:?} is not three numbers",
            path.display()
        ),
    }
}

/// Every range a data line lists, `XXXX..YYYY ; age` or `XXXX ; age`, its
/// comment removed; blank and comment lines skipped. A line of any other
/// form, or a range outside the code space or reversed, fails the build
/// naming its line.
fn assigned_ranges(text: &str, path: &Path) -> Vec<(u32, u32)> {
    let mut ranges = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let data = line.split('#').next().unwrap_or_default().trim();
        if data.is_empty() {
            continue;
        }
        let at = || format!("{}:{}", path.display(), index + 1);
        let (points, age) = data
            .split_once(';')
            .unwrap_or_else(|| panic!("{}: {line:?} has no age field", at()));
        if age.trim().is_empty() {
            panic!("{}: {line:?} has an empty age", at());
        }
        let points = points.trim();
        let (start, end) = match points.split_once("..") {
            Some((start, end)) => (hex(start, &at), hex(end, &at)),
            None => {
                let point = hex(points, &at);
                (point, point)
            }
        };
        if start > end || end > 0x10_FFFF {
            panic!(
                "{}: range {start:04X}..{end:04X} is reversed or past U+10FFFF",
                at()
            );
        }
        ranges.push((start, end));
    }
    if ranges.is_empty() {
        panic!("{} lists no assigned code point", path.display());
    }
    ranges
}

fn hex(text: &str, at: &dyn Fn() -> String) -> u32 {
    u32::from_str_radix(text.trim(), 16)
        .unwrap_or_else(|error| panic!("{}: {text:?} is not a code point: {error}", at()))
}

/// `ranges` sorted and merged: overlapping and adjacent ranges joined, so
/// the table is the fewest disjoint, non-adjacent ranges.
fn merged(mut ranges: Vec<(u32, u32)>) -> Vec<(u32, u32)> {
    ranges.sort_unstable();
    let mut joined: Vec<(u32, u32)> = Vec::with_capacity(ranges.len());
    for (start, end) in ranges {
        match joined.last_mut() {
            Some(last) if start <= last.1.saturating_add(1) => last.1 = last.1.max(end),
            _ => joined.push((start, end)),
        }
    }
    joined
}
